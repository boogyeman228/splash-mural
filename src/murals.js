/** Pixels of a mural: [{ x, y, c }] for every painted cell (c = palette id). */
export function pixelsOf(mural) {
  const out = [];
  mural.art.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch !== '.') out.push({ x, y, c: KEY_TO_ID[ch] });
    }
  });
  return out;
}
